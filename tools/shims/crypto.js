const utf8 = (s) => new TextEncoder().encode(s);
const rotl = (x, n) => (x << n) | (x >>> (32 - n));
const rotr = (x, n) => (x >>> n) | (x << (32 - n));
function pad(bytes) {
  const len = bytes.length, bits = len * 8, total = (((len + 9 + 63) >> 6) << 6);
  const m = new Uint8Array(total); m.set(bytes); m[len] = 0x80;
  const dv = new DataView(m.buffer); dv.setUint32(total - 4, bits >>> 0); dv.setUint32(total - 8, Math.floor(bits / 2 ** 32));
  return dv;
}
